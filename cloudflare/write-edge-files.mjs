#!/usr/bin/env node
/**
 * Post-build: write Cloudflare's `_headers` and `_redirects` into `out/`.
 *
 * Runs as `postbuild`, so every `npm run build` produces a directory that is
 * ready for `npx wrangler deploy` (see wrangler.jsonc and
 * docs/cloudflare-deployment.md).
 *
 * _headers   security headers on every path (from security-headers.mjs), and
 *            a one-year immutable cache on /_next/static/*, whose file names
 *            are content hashes. Everything else keeps Cloudflare's default
 *            revalidating cache, as Netlify served it.
 *
 * _redirects one rule: a trailing slash is removed with a 308, the status the
 *            Next.js server returned for `trailingSlash: false`. Without it the
 *            asset handler would answer the same request with a 307.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SECURITY_HEADERS } from './security-headers.mjs';

const OUT = join(process.cwd(), 'out');
if (!existsSync(OUT)) {
  console.error(
    'write-edge-files: out/ does not exist — run `next build` first',
  );
  process.exit(1);
}

const securityLines = SECURITY_HEADERS.map((h) => `  ${h.key}: ${h.value}`);
const headers = [
  '# Generated by cloudflare/write-edge-files.mjs — do not edit.',
  '/*',
  ...securityLines,
  '',
  '/_next/static/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
].join('\n');

const redirects = [
  '# Generated by cloudflare/write-edge-files.mjs — do not edit.',
  '/*/ /:splat 308',
  '',
].join('\n');

writeFileSync(join(OUT, '_headers'), headers);
writeFileSync(join(OUT, '_redirects'), redirects);
console.log('write-edge-files: wrote out/_headers and out/_redirects');
